"""Zag code generator: translates the AST into Zig source.

Core responsibilities:
1. **Four Pillars semantics** — const / var / const? / var. usage rules;
2. **Type mapping** — int->i32, float->f64, string->[]const u8 ...;
3. **Zig idiom adaptation** — std.print->std.debug.print, @intCast on indices,
   explicit type on var literals, blk: value blocks for catch/if, etc.

All Zig behaviors in the generation strategy are verified on Zig 0.17.0.
"""

from . import ast_nodes as ast


class ZagError(Exception):
    """Zag semantic error (e.g. Four Pillars rule violations)."""

    def __init__(self, message, line=0, col=0):
        super().__init__(message)
        self.message = message
        self.line = line
        self.col = col

    def __str__(self):
        if self.line:
            return f"{self.line}:{self.col}: {self.message}"
        return self.message


class VarInfo:
    """How a variable is used within a scope (the basis for Four Pillars checks)."""

    __slots__ = ("kind", "mutated", "read", "address_taken")

    def __init__(self, kind):
        self.kind = kind
        self.mutated = False        # whether directly assigned (= / += / ++ / $x = )
        self.read = False           # whether read (including taking its address)
        self.address_taken = False  # whether its address was taken (may be mutated indirectly via pointer)


class CodeGen:
    # Zag type -> Zig type
    TYPE_MAP = {
        "int": "i32",
        "float": "f64",
        "bool": "bool",
        "string": "[]const u8",
        "void": "void",
        "type": "type",
        "u8": "u8",
        "u16": "u16",
        "u32": "u32",
        "u64": "u64",
        "i8": "i8",
        "i16": "i16",
        "i64": "i64",
        "usize": "usize",
        "isize": "isize",
    }

    def __init__(self, filename="<stdin>", source_dir="."):
        self.filename = filename
        self.source_dir = source_dir
        self.out = []
        self.indent = 0
        self.errors = []
        # Type info table (drives std.print format-spec inference, best effort)
        self.fn_returns = {}      # function name -> Zag return type name
        self.fn_ret_nodes = {}    # function name -> return type AST node (raw, incl. error/generic)
        self.struct_fields = {}   # struct name -> {field name: type name}
        self.var_types = {}       # variable name -> Zag type name
        # .zag imports to compile recursively: [(original path, source dir)]
        self.pending_imports = []
        # Current scope context (needed during expression generation)
        self._infos = {}
        self._is_local = False
        # Whether the runtime prelude (zag_concat / zag_to_upper / zag_find) was used
        self.used_prelude = False
        # Enclosing type name when generating a struct method (for self pointerization)
        self._current_self_type = None

# ============================================================ output helpers
    def emit(self, text):
        self.out.append("    " * self.indent + text)

    def blank(self):
        self.out.append("")

    def _error(self, message, line, col):
        self.errors.append(f"{line}:{col}: {message}")

# ============================================================ entry
    def generate(self, program):
        self._collect_decls(program)

        self.emit("// " + "=" * 62)
        self.emit("// This file was auto-generated by the Zag compiler; do not edit manually")
        self.emit(f"// source: {self.filename}")
        self.emit("// " + "=" * 62)
        self.blank()

        global_infos = self._analyze_globals(program)

        if self.used_prelude:
            self._emit_prelude()
            self.blank()

        for item in program.items:
            self._gen_toplevel(item, global_infos)

        if self.errors:
            details = "\n".join(f"  {e}" for e in self.errors)
            raise ZagError(f"发现 {len(self.errors)} 个语义错误:\n{details}")
        return "\n".join(self.out) + "\n"

# ============================================================ generic / collection helpers
    def _zig_generic_type(self, t):
        """GenericType (type position) -> concrete Zig type.

        std.List(T)       -> std.array_list.Managed(T)   (Zig 0.17 verified)
        std.Map(string,V) -> std.StringHashMap(V)
        std.Map(K,V)      -> std.AutoHashMap(K, V)
        """
        if t.base in ("std.List", "std.ArrayList"):
            inner = self.zig_type(t.args[0]) if t.args else "i32"
            return f"std.array_list.Managed({inner})"
        if t.base == "std.Map":
            if len(t.args) >= 2:
                k, v = t.args[0], self.zig_type(t.args[1])
                if isinstance(k, ast.TypeRef) and k.name == "string":
                    return f"std.StringHashMap({v})"
                return f"std.AutoHashMap({self.zig_type(k)}, {v})"
            return "std.AutoHashMap(i32, i32)"
        # Unknown generic: emit the base name verbatim (best effort)
        return t.base

    def _elem_id(self, arg):
        """Element/key type name for a generic argument (used inside List/Map ids)."""
        if arg is None:
            return "i32"
        if isinstance(arg, ast.TypeRef):
            return arg.name
        if isinstance(arg, ast.Ident):
            return arg.name
        if isinstance(arg, ast.GenericType):
            return arg.base
        return "i32"

    def _type_id(self, t):
        """A short id used to remember a variable/field's *kind* for later rewrites.

        "List:<elem>" / "Map" mark collection variables; plain type names pass through.
        """
        if t is None:
            return None
        if isinstance(t, ast.GenericType):
            if t.base in ("std.List", "std.ArrayList"):
                return "List:" + self._elem_id(t.args[0]) if t.args else "List"
            if t.base == "std.Map":
                return "Map"
            return t.base
        if isinstance(t, ast.TypeRef):
            return t.name
        return None

    def _arg_as_type(self, arg):
        """A constructor's first argument is a *type* written in expression position.

        It may arrive as a TypeRef (int), an Ident (Token / int), or a GenericType
        (std.List(Token)). Map all of these to a concrete Zig type name.
        """
        if arg is None:
            return "i32"
        if isinstance(arg, ast.TypeRef):
            return self.TYPE_MAP.get(arg.name, arg.name)
        if isinstance(arg, ast.GenericType):
            return self._zig_generic_type(arg)
        if isinstance(arg, ast.Ident):
            return self.TYPE_MAP.get(arg.name, arg.name)
        return "i32"

    def _base_collection_kind(self, base):
        """Returns 'list' / 'map' / 'string' / None for a base expression."""
        t = self.static_type(base)
        if t is None:
            return None
        if t.startswith("List"):
            return "list"
        if t.startswith("Map"):
            return "map"
        if t == "string":
            return "string"
        return None

    def _emit_prelude(self):
        """Emits the runtime helper functions required by List/Map/string methods.

        All signatures are verified against Zig 0.17.0.
        """
        self.emit("// --- Zag runtime prelude (auto-injected) ---")
        self.emit("fn zag_concat(alloc: std.mem.Allocator, a: []const u8, b: []const u8) []const u8 {")
        self.emit("    return std.mem.concat(alloc, u8, &[_][]const u8{ a, b }) catch @panic(\"OOM\");")
        self.emit("}")
        self.blank()
        self.emit("fn zag_to_upper(alloc: std.mem.Allocator, s: []const u8) []const u8 {")
        self.emit("    const buf = alloc.alloc(u8, s.len) catch @panic(\"OOM\");")
        self.emit("    _ = std.ascii.upperString(buf, s);")
        self.emit("    return buf;")
        self.emit("}")
        self.blank()
        self.emit("fn zag_find(s: []const u8, sub: []const u8) i32 {")
        self.emit("    const r = std.mem.indexOf(u8, s, sub);")
        self.emit("    if (r) |v| return @intCast(v);")
        self.emit("    return -1;")
        self.emit("}")
        self.blank()

# ============================================================ pre-scan
    def _collect_decls(self, program):
        """Collects function return types, struct fields, top-level variable types for format inference."""
        for item in program.items:
            if isinstance(item, ast.FnDecl):
                self.fn_ret_nodes[item.name] = item.ret_type
                tid = self._type_id(item.ret_type)
                if tid is not None:
                    self.fn_returns[item.name] = tid
            elif isinstance(item, ast.StructDecl):
                self.struct_fields[item.name] = {
                    f.name: self._type_id(f.type) for f in item.fields
                }
                self._collect_method_returns(item.name, item.methods)
            elif isinstance(item, ast.UnionDecl):
                self.struct_fields[item.name] = {
                    f.name: self._type_id(f.type) for f in item.fields
                }
                self._collect_method_returns(item.name, item.methods)
            elif isinstance(item, ast.VarDecl):
                self._record_var_type(item)
                # const m = @import("x.zag") — pre-scan imported module's types.
                # Handles both a direct import and a member import (type import)
                # such as `const Token = @import("ast_nodes.zag").Token`.
                self._collect_imports_from_value(item.value, item.name)

    def _collect_imports_from_value(self, value, alias):
        if isinstance(value, ast.ImportExpr):
            self._collect_import_returns(alias, value.path)
        elif isinstance(value, ast.Field) and isinstance(value.base, ast.ImportExpr):
            # member (type) import: struct fields / method returns are keyed by
            # their real type name, so the alias is irrelevant here.
            self._collect_import_returns("_", value.base.path)

    def _collect_method_returns(self, type_name, methods):
        """Registers '<Type>.<method>' -> return type so method-call results infer correctly."""
        for m in methods:
            self.fn_ret_nodes[f"{type_name}.{m.name}"] = m.ret_type
            tid = self._type_id(m.ret_type)
            if tid is not None:
                self.fn_returns[f"{type_name}.{m.name}"] = tid

    def _collect_import_returns(self, alias, path):
        """Loads an imported .zag module and registers 'module.fn' -> return type (best effort).

        Also registers the module's struct/class field types and method return
        types (by type name) so format-spec inference works across modules.
        """
        if not path.endswith(".zag"):
            return
        import os
        full = os.path.join(self.source_dir, path)
        try:
            with open(full, "r", encoding="utf-8") as f:
                src = f.read()
            from .parser import parse as _parse
            prog = _parse(src)
        except Exception:
            return  # module missing or parse failed: let the Zig compile stage report the error
        for item in prog.items:
            if isinstance(item, ast.FnDecl):
                tid = self._type_id(item.ret_type)
                if item.pub and tid is not None:
                    self.fn_returns[f"{alias}.{item.name}"] = tid
            elif isinstance(item, (ast.StructDecl, ast.UnionDecl)):
                self.struct_fields[item.name] = {
                    f.name: self._type_id(f.type) for f in item.fields
                }
                self._collect_method_returns(item.name, item.methods)
            elif isinstance(item, ast.VarDecl):
                self._record_var_type(item)

    def _record_var_type(self, decl):
        if decl.type is not None:
            self.var_types[decl.name] = self._type_id(decl.type)
        elif isinstance(decl.value, (ast.StructDecl, ast.EnumDecl, ast.UnionDecl)):
            # const Point = struct { ... } — the name itself becomes a type name
            self.var_types[decl.name] = decl.name
            if not isinstance(decl.value, ast.EnumDecl):
                self.struct_fields[decl.name] = {
                    f.name: self._type_id(f.type) for f in decl.value.fields
                }
        elif decl.value is not None:
            cid = self._call_collection_id(decl.value)
            if cid:
                self.var_types[decl.name] = cid
            else:
                t = self.static_type(decl.value)
                if t:
                    self.var_types[decl.name] = t

    def _call_collection_id(self, e):
        """If `e` is a std.List / std.Map constructor call, return its collection id.

        'List:<elem>' for lists (so element types survive inference) and 'Map' for maps.
        Handles both `std.List(...)` (Field callee) and `List(...)` (Ident callee) forms.
        """
        if not isinstance(e, ast.Call):
            return None
        name = None
        if isinstance(e.callee, ast.Ident):
            name = e.callee.name
        elif isinstance(e.callee, ast.Field) and isinstance(e.callee.base, ast.Ident) \
                and e.callee.base.name == "std":
            name = "std." + e.callee.name
        if name in ("std.List", "std.ArrayList"):
            return "List:" + self._elem_id(e.args[0]) if e.args else "List"
        if name == "std.Map":
            return "Map"
        return None

# ============================================================ scope analysis
    def _analyze_globals(self, program):
        """Container-level scope: register top-level declarations and walk all function bodies for references/assignments."""
        infos = {}

        def register(name, kind):
            if name not in infos:
                infos[name] = VarInfo(kind)

        for item in program.items:
            if isinstance(item, ast.VarDecl):
                register(item.name, item.kind)
                self._visit_expr(item.value, infos, None)
            elif isinstance(item, ast.DestructureDecl):
                for t in item.targets:
                    register(t, item.kind)
                self._visit_expr(item.value, infos, None)

        # Walk all function bodies (incl. struct methods, test blocks); shadow local names to avoid polluting globals
        containers = []
        for item in program.items:
            if isinstance(item, ast.FnDecl) and item.body:
                containers.append(item.body)
            elif isinstance(item, ast.TestDecl):
                containers.append(item.body)
            elif isinstance(item, (ast.StructDecl, ast.EnumDecl, ast.UnionDecl)):
                containers.extend(m.body for m in item.methods if m.body)
            elif isinstance(item, ast.VarDecl) and isinstance(
                    item.value, (ast.StructDecl, ast.EnumDecl, ast.UnionDecl)):
                # const Point = struct { fn method() ... } — methods inside a value are also analyzed
                containers.extend(m.body for m in item.value.methods if m.body)
        for body in containers:
            locals_ = self._collect_local_names(body)
            self._visit_stmts(body.stmts, infos, locals_)
        return infos

    def _analyze_scope(self, stmts):
        """Function-local scope analysis."""
        infos = {}
        self._visit_stmts(stmts, infos, None)
        return infos

    def _collect_local_names(self, body):
        """Collects all local names declared inside one function body (excluding nested functions)."""
        names = set()

        def walk(stmts):
            for s in stmts:
                if isinstance(s, ast.VarDecl):
                    names.add(s.name)
                elif isinstance(s, ast.DestructureDecl):
                    names.update(s.targets)
                elif isinstance(s, ast.FnDecl):
                    continue  # nested function is an independent scope
                elif isinstance(s, ast.Block):
                    walk(s.stmts)
                elif isinstance(s, ast.IfStmt):
                    walk([s.then_stmt] if not isinstance(s.then_stmt, ast.Block) else s.then_stmt.stmts)
                    if s.else_stmt is not None:
                        walk([s.else_stmt] if not isinstance(s.else_stmt, ast.Block) else s.else_stmt.stmts)
                elif isinstance(s, ast.WhileStmt):
                    walk([s.body] if not isinstance(s.body, ast.Block) else s.body.stmts)
                elif isinstance(s, ast.ForStmt):
                    parts = [p for p in (s.init, s.post) if p is not None]
                    walk(parts)
                    walk([s.body] if not isinstance(s.body, ast.Block) else s.body.stmts)
                elif isinstance(s, ast.DeferStmt):
                    walk([s.body] if not isinstance(s.body, ast.Block) else s.body.stmts)
                elif isinstance(s, ast.ComptimeStmt):
                    walk(s.body.stmts)

        walk(body.stmts)
        return names

    # ---- Visitor: mark mutated / read / address_taken
    def _visit_stmts(self, stmts, infos, skip):
        for s in stmts:
            self._visit_stmt(s, infos, skip)

    def _visit_stmt(self, s, infos, skip):
        if isinstance(s, ast.VarDecl):
            if skip is None or s.name not in skip:
                infos.setdefault(s.name, VarInfo(s.kind))
            self._visit_expr(s.value, infos, skip)
        elif isinstance(s, ast.DestructureDecl):
            for t in s.targets:
                if skip is None or t not in skip:
                    infos.setdefault(t, VarInfo(s.kind))
            self._visit_expr(s.value, infos, skip)
        elif isinstance(s, ast.FnDecl):
            return  # nested function is an independent scope
        elif isinstance(s, ast.ExprStmt):
            self._visit_expr(s.expr, infos, skip)
        elif isinstance(s, ast.AssignStmt):
            target = s.target
            if isinstance(target, ast.Ident):
                if skip is None or target.name not in skip:
                    info = infos.get(target.name)
                    if info is not None:
                        info.mutated = True
            elif isinstance(target, ast.Field):
                # `n.field = ...` (or `n.a.b = ...`) requires n to be mutable.
                root = target.base
                while isinstance(root, ast.Field):
                    root = root.base
                if isinstance(root, ast.Ident) and (skip is None or root.name not in skip):
                    info = infos.get(root.name)
                    if info is not None:
                        info.mutated = True
                self._visit_expr(target.base, infos, skip)
            else:
                self._visit_expr(target, infos, skip)
            self._visit_expr(s.value, infos, skip)
        elif isinstance(s, ast.IncDecStmt):
            target = s.target
            if isinstance(target, ast.Ident):
                if skip is None or target.name not in skip:
                    info = infos.get(target.name)
                    if info is not None:
                        info.mutated = True
            elif isinstance(target, ast.Field):
                root = target.base
                while isinstance(root, ast.Field):
                    root = root.base
                if isinstance(root, ast.Ident) and (skip is None or root.name not in skip):
                    info = infos.get(root.name)
                    if info is not None:
                        info.mutated = True
            else:
                self._visit_expr(target, infos, skip)
        elif isinstance(s, ast.ReturnStmt):
            self._visit_expr(s.value, infos, skip)
        elif isinstance(s, ast.IfStmt):
            self._visit_expr(s.cond, infos, skip)
            self._visit_stmt(s.then_stmt, infos, skip)
            if s.else_stmt is not None:
                self._visit_stmt(s.else_stmt, infos, skip)
        elif isinstance(s, ast.WhileStmt):
            self._visit_expr(s.cond, infos, skip)
            self._visit_stmt(s.body, infos, skip)
        elif isinstance(s, ast.ForStmt):
            for part in (s.init, s.post):
                if part is not None:
                    self._visit_stmt(part, infos, skip)
            self._visit_expr(s.cond, infos, skip)
            self._visit_stmt(s.body, infos, skip)
        elif isinstance(s, ast.DeferStmt):
            self._visit_stmt(s.body, infos, skip)
        elif isinstance(s, ast.ComptimeStmt):
            self._visit_stmts(s.body.stmts, infos, skip)
        elif isinstance(s, ast.Block):
            self._visit_stmts(s.stmts, infos, skip)
        # Other declarations have no variable references

    def _visit_expr(self, e, infos, skip):
        if e is None:
            return
        if isinstance(e, ast.Ident):
            if skip is None or e.name not in skip:
                info = infos.get(e.name)
                if info is not None:
                    info.read = True
        elif isinstance(e, ast.AddressOf):
            self._visit_expr(e.operand, infos, skip)
            if isinstance(e.operand, ast.Ident):
                if skip is None or e.operand.name not in skip:
                    info = infos.get(e.operand.name)
                    if info is not None:
                        info.read = True
                        info.address_taken = True
        elif isinstance(e, ast.Deref):
            self._visit_expr(e.operand, infos, skip)
            if isinstance(e.operand, ast.Ident):
                if skip is None or e.operand.name not in skip:
                    info = infos.get(e.operand.name)
                    if info is not None:
                        info.read = True
        elif isinstance(e, ast.Binary):
            self._visit_expr(e.left, infos, skip)
            self._visit_expr(e.right, infos, skip)
        elif isinstance(e, ast.ConcatExpr):
            self.used_prelude = True
            self._visit_expr(e.left, infos, skip)
            self._visit_expr(e.right, infos, skip)
        elif isinstance(e, ast.Unary):
            self._visit_expr(e.operand, infos, skip)
        elif isinstance(e, ast.Call):
            if isinstance(e.callee, ast.Field) and e.callee.name in ("to_upper", "find"):
                self.used_prelude = True
            self._visit_expr(e.callee, infos, skip)
            for a in e.args:
                self._visit_expr(a, infos, skip)
            # Method calls on an object may mutate the receiver (e.g. list.append,
            # map.set, or any class method that writes to `self`), so a `var`
            # declaration isn't falsely flagged as never-mutated. Const receivers
            # are skipped: a read-only-looking method call must not imply assignment.
            if isinstance(e.callee, ast.Field):
                base = e.callee.base
                if isinstance(base, ast.Ident) and (skip is None or base.name not in skip):
                    info = infos.get(base.name)
                    if info is not None and info.kind != "const":
                        info.mutated = True
        elif isinstance(e, ast.Index):
            self._visit_expr(e.base, infos, skip)
            self._visit_expr(e.index, infos, skip)
        elif isinstance(e, ast.SliceExpr):
            self._visit_expr(e.base, infos, skip)
            self._visit_expr(e.start, infos, skip)
            self._visit_expr(e.end, infos, skip)
        elif isinstance(e, ast.Field):
            self._visit_expr(e.base, infos, skip)
        elif isinstance(e, ast.ArrayLit):
            for x in e.elems:
                self._visit_expr(x, infos, skip)
        elif isinstance(e, ast.StructLit):
            for _, v in e.fields:
                self._visit_expr(v, infos, skip)
        elif isinstance(e, ast.IfExpr):
            self._visit_expr(e.cond, infos, skip)
            self._visit_expr(e.then_expr, infos, skip)
            self._visit_expr(e.else_expr, infos, skip)
        elif isinstance(e, ast.ErrorSetLit):
            pass  # only an error name, no variable reference
        elif isinstance(e, ast.TryExpr):
            self._visit_expr(e.expr, infos, skip)
        elif isinstance(e, ast.CatchExpr):
            self._visit_expr(e.expr, infos, skip)
            self._visit_expr(e.payload, infos, skip)
        elif isinstance(e, ast.BuiltinCall):
            for a in e.args:
                self._visit_expr(a, infos, skip)

# ============================================================ Four Pillars resolution
    def _resolve(self, kind, name, info, is_local, line, col):
        """Returns (zig declaration keyword, need _ = &x to silence unused, need x = x self-assignment)."""
        if kind == "const":
            if info.mutated:
                self._error(
                    f"不能给常量 '{name}' 赋值（常量不可变；若希望静默忽略修改，请使用 const?）",
                    line, col)
            if is_local and not info.read:
                self._error(
                    f"常量 '{name}' 声明后从未使用（若希望允许未使用，请使用 const?）",
                    line, col)
            return "const", False, False

        if kind == "const_safe":
            # const? : assignment is silently discarded at generation, program continues
            return "const", (is_local and not info.read), False

        # var / var_safe
        if info.mutated:
            return "var", False, False
        if info.address_taken:
            # After taking its address it may be mutated indirectly via pointer; conservatively keep var
            return "var", False, is_local
        if kind == "var":
            self._error(
                f"var '{name}' 声明后从未被修改（若希望静默忽略，请使用 var.）",
                line, col)
            return "var", False, False
        # var_safe that was never mutated nor addressed: safely degrade to const
        return "const", (is_local and not info.read), False

# ============================================================ top-level declarations
    def _gen_toplevel(self, item, global_infos):
        # Top-level declarations are part of a module's public API, so they are
        # emitted `pub` by default. This lets other files import them via
        # @import("module.zag").Name. `pub fn main` is already pub (user-written).
        if isinstance(item, (ast.FnDecl, ast.VarDecl, ast.StructDecl,
                             ast.EnumDecl, ast.UnionDecl)):
            item.pub = True
        if isinstance(item, ast.FnDecl):
            self._gen_fn(item)
            self.blank()
        elif isinstance(item, ast.StructDecl):
            self._gen_struct(item)
            self.blank()
        elif isinstance(item, ast.EnumDecl):
            self._gen_enum(item)
            self.blank()
        elif isinstance(item, ast.UnionDecl):
            self._gen_union(item)
            self.blank()
        elif isinstance(item, ast.VarDecl):
            self._gen_var_decl(item, global_infos, is_local=False)
            self.blank()
        elif isinstance(item, ast.DestructureDecl):
            self._gen_destructure(item, global_infos, is_local=False)
            self.blank()
        elif isinstance(item, ast.TestDecl):
            self._gen_test(item)
            self.blank()
        elif isinstance(item, ast.ComptimeStmt):
            # Top-level comptime block handled as a local scope
            infos = self._analyze_scope(item.body.stmts)
            saved = (self._infos, self._is_local)
            self._infos, self._is_local = infos, True
            self.emit("comptime {")
            self._gen_body(item.body)
            self.emit("}")
            self._infos, self._is_local = saved
            self.blank()

    def _gen_fn(self, fn):
        prefix = ""
        if fn.pub:
            prefix += "pub "
        if fn.export:
            prefix += "export "
        if fn.extern:
            prefix += "extern "
        if fn.inline:
            prefix += "inline "
        parts = []
        for i, p in enumerate(fn.params):
            if i == 0 and p.name == "self" and self._current_self_type is not None:
                # Method receiver: rewrite `self` to `self: *EnclosingType`.
                # Use a const pointer when the method never mutates self (Zig idiom).
                const = "" if self._method_mutates_self(fn.body) else "const "
                parts.append(f"self: *{const}{self._current_self_type}")
            else:
                parts.append(f"{'comptime ' if p.comptime else ''}{p.name}: {self.zig_type(p.type)}")
        params = ", ".join(parts)
        ret = f" {self.zig_type(fn.ret_type)}" if fn.ret_type is not None else ""

        if fn.extern:
            self.emit(f"{prefix}fn {fn.name}({params}){ret};")
            return

        self.emit(f"{prefix}fn {fn.name}({params}){ret} {{")
        self.indent += 1
        infos = self._analyze_scope(fn.body.stmts)
        saved = (self._infos, self._is_local)
        self._infos, self._is_local = infos, True
        for st in fn.body.stmts:
            self._gen_stmt(st)
        self._infos, self._is_local = saved
        self.indent -= 1
        self.emit("}")

    def _emit_aggregate(self, kw, decl, header):
        """Emits the struct/enum/union body; header is a prefix like 'const Name = '."""
        self.emit(header + kw + " {")
        self.indent += 1
        if kw == "enum":
            for v in decl.variants:
                if v.value is not None:
                    self.emit(f"{v.name} = {self.expr(v.value)},")
                else:
                    self.emit(f"{v.name},")
        else:
            for f in decl.fields:
                self.emit(f"{f.name}: {self.zig_type(f.type)},")
        saved_self = self._current_self_type
        for m in decl.methods:
            self._current_self_type = decl.name
            m.pub = True  # class/struct methods are part of the type's public API
            self._gen_fn(m)
        self._current_self_type = saved_self
        self.indent -= 1
        self.emit("};")

    def _gen_struct(self, decl):
        self._emit_aggregate("struct", decl,
                             f"{'pub ' if decl.pub else ''}const {decl.name} = ")

    def _gen_enum(self, decl):
        self._emit_aggregate("enum", decl,
                             f"{'pub ' if decl.pub else ''}const {decl.name} = ")

    def _gen_union(self, decl):
        self._emit_aggregate("union", decl,
                             f"{'pub ' if decl.pub else ''}const {decl.name} = ")

    def _gen_test(self, decl):
        self.emit(f'test "{decl.name}" {{')
        self.indent += 1
        infos = self._analyze_scope(decl.body.stmts)
        saved = (self._infos, self._is_local)
        self._infos, self._is_local = infos, True
        for st in decl.body.stmts:
            self._gen_stmt(st)
        self._infos, self._is_local = saved
        self.indent -= 1
        self.emit("}")

# ============================================================ variable declarations
    def _gen_var_decl(self, decl, infos, is_local):
        info = infos.get(decl.name) or VarInfo(decl.kind)
        zig_kind, discard, self_assign = self._resolve(
            decl.kind, decl.name, info, is_local, decl.line, decl.col)

            # const Point = struct { ... } — aggregate type literal, emit multi-line
        if isinstance(decl.value, (ast.StructDecl, ast.EnumDecl, ast.UnionDecl)):
            kw = ("enum" if isinstance(decl.value, ast.EnumDecl)
                  else "union" if isinstance(decl.value, ast.UnionDecl)
                  else "struct")
            pub = "pub " if decl.pub else ""
            self._emit_aggregate(kw, decl.value, f"{pub}{zig_kind} {decl.name} = ")
            self._record_var_type(decl)
            return

        type_str = ""
        if decl.type is not None:
            type_str = ": " + self.zig_type(decl.type)
        elif decl.value is not None:
            ann = self._literal_annotation(decl.value)
            if ann is not None:
                type_str = ": " + ann

        value_str = self.expr(decl.value) if decl.value is not None else "undefined"
        pub = "pub " if decl.pub else ""
        self.emit(f"{pub}{zig_kind} {decl.name}{type_str} = {value_str};")
        if self_assign:
            # After taking the address it may be mutated indirectly via pointer; keep var conservatively;
            # Zig requires a var to be directly assigned at least once, so emit a self-assignment
            self.emit(f"{decl.name} = {decl.name};")
        if discard:
            self.emit(f"_ = &{decl.name};")
        self._record_var_type(decl)

    def _gen_destructure(self, decl, infos, is_local):
        for i, target in enumerate(decl.targets):
            info = infos.get(target) or VarInfo(decl.kind)
            zig_kind, discard, _ = self._resolve(
                decl.kind, target, info, is_local, decl.line, decl.col)
            self.emit(f"{zig_kind} {target} = {self.expr(decl.value)}[{i}];")
            if discard:
                self.emit(f"_ = &{target};")

    def _literal_annotation(self, value):
        """Type annotation for literal initial values: a Zig var cannot be comptime_int, must be explicitly typed."""
        if isinstance(value, ast.IntLit):
            return "i32"
        if isinstance(value, ast.FloatLit):
            return "f64"
        if isinstance(value, ast.StringLit):
            return "[]const u8"
        if isinstance(value, ast.BoolLit):
            return "bool"
        return None

# ============================================================ statements
    def _gen_stmt(self, s):
        if isinstance(s, ast.VarDecl):
            self._gen_var_decl(s, self._infos, self._is_local)
        elif isinstance(s, ast.DestructureDecl):
            self._gen_destructure(s, self._infos, self._is_local)
        elif isinstance(s, ast.FnDecl):
            self._gen_fn(s)
        elif isinstance(s, ast.StructDecl):
            self._gen_struct(s)
        elif isinstance(s, ast.EnumDecl):
            self._gen_enum(s)
        elif isinstance(s, ast.UnionDecl):
            self._gen_union(s)
        elif isinstance(s, ast.TestDecl):
            self._gen_test(s)
        elif isinstance(s, ast.ExprStmt):
            e = s.expr
            if isinstance(e, ast.Call):
                # Collection mutation methods return !void; ignore the error.
                if (isinstance(e.callee, ast.Field)
                        and e.callee.name in ("append", "appendSlice", "insert", "prepend")
                        and self._base_collection_kind(e.callee.base) == "list"):
                    self.emit(f"{self.expr(e)} catch {{}};")
                else:
                    mode = self._stmt_suffix(e)
                    if mode == "error":
                        self.emit(f"{self.expr(e)} catch {{}};")
                    elif mode == "value":
                        self.emit(f"_ = {self.expr(e)};")
                    else:
                        self.emit(f"{self.expr(e)};")
            else:
                self.emit(self.expr(s.expr) + ";")
        elif isinstance(s, ast.AssignStmt):
            self._gen_assign(s)
        elif isinstance(s, ast.IncDecStmt):
            self._gen_incdec(s)
        elif isinstance(s, ast.ReturnStmt):
            if s.value is not None:
                self.emit(f"return {self.expr(s.value)};")
            else:
                self.emit("return;")
        elif isinstance(s, ast.IfStmt):
            self._gen_if(s)
        elif isinstance(s, ast.WhileStmt):
            prefix = f"{s.label}: " if s.label else ""
            self.emit(f"{prefix}while ({self.expr(s.cond)}) {{")
            self._gen_body(s.body)
            self.emit("}")
        elif isinstance(s, ast.ForStmt):
            self._gen_for(s)
        elif isinstance(s, ast.DeferStmt):
            self.emit("defer {")
            self._gen_body(s.body)
            self.emit("}")
        elif isinstance(s, ast.ComptimeStmt):
            self.emit("comptime {")
            self._gen_body(s.body)
            self.emit("}")
        elif isinstance(s, ast.Block):
            self.emit("{")
            self._gen_body(s)
            self.emit("}")
        elif isinstance(s, ast.BreakStmt):
            self.emit(f"break{(' : ' + s.label) if s.label else ''};")
        elif isinstance(s, ast.ContinueStmt):
            self.emit(f"continue{(' : ' + s.label) if s.label else ''};")
        else:
            raise ZagError(f"代码生成器遇到未知语句: {type(s).__name__}")

    def _gen_body(self, body):
        """body may be a Block or a single statement, indented uniformly."""
        self.indent += 1
        if isinstance(body, ast.Block):
            for st in body.stmts:
                self._gen_stmt(st)
        else:
            self._gen_stmt(body)
        self.indent -= 1

    def _gen_assign(self, s):
            # const? assignment is silently discarded (keep the right-hand side side effects)
        if isinstance(s.target, ast.Ident):
            info = self._infos.get(s.target.name)
            if info is not None and info.kind == "const_safe":
                self.emit(f"_ = {self.expr(s.value)};")
                return
        self.emit(f"{self.expr(s.target)} {s.op} {self.expr(s.value)};")

    def _gen_incdec(self, s):
        if isinstance(s.target, ast.Ident):
            info = self._infos.get(s.target.name)
            if info is not None and info.kind == "const_safe":
                sign = "+" if s.op == "++" else "-"
                self.emit(f"_ = {self.expr(s.target)} {sign} 1;")
                return
        op = "+=" if s.op == "++" else "-="
        self.emit(f"{self.expr(s.target)} {op} 1;")

    def _gen_if(self, s):
        # Expand the else-if chain into Zig's idiomatic } else if (...) {
        parts = [s]
        while isinstance(parts[-1].else_stmt, ast.IfStmt):
            parts.append(parts[-1].else_stmt)
        for idx, part in enumerate(parts):
            cond = self.expr(part.cond)
            # The if payload performs the unpack; use |_| placeholder when unused (Zig 0.17 requirement)
            cap = ""
            if getattr(part, "payload", None):
                if (self._name_used(part.then_stmt, part.payload)
                        or self._name_used(part.else_stmt, part.payload)):
                    cap = f" |{part.payload}|"
                else:
                    cap = " |_|"
            if idx == 0:
                self.emit(f"if ({cond}){cap} {{")
            else:
                self.emit(f"}} else if ({cond}){cap} {{")
            self._gen_body(part.then_stmt)
        last = parts[-1]
        if last.else_stmt is None:
            self.emit("}")
        else:
            self.emit("} else {")
            self._gen_body(last.else_stmt)
            self.emit("}")

    def _gen_for(self, s):
        # Zag's C-style for -> Zig's while + continue expression
        if s.init is not None:
            if isinstance(s.init, ast.VarDecl):
                self._gen_var_decl(s.init, self._infos, self._is_local)
            elif isinstance(s.init, (ast.AssignStmt, ast.IncDecStmt)):
                self._gen_stmt(s.init)
            elif isinstance(s.init, ast.ExprStmt):
                self.emit(self.expr(s.init.expr) + ";")
        cond = self.expr(s.cond) if s.cond is not None else "true"
        header = f"while ({cond})"
        if s.post is not None:
            header += f" : ({self._post_expr(s.post)})"
        if s.label:
            header = f"{s.label}: " + header
        self.emit(header + " {")
        self._gen_body(s.body)
        self.emit("}")

    def _post_expr(self, post):
        if isinstance(post, ast.IncDecStmt):
            op = "+=" if post.op == "++" else "-="
            return f"{self.expr(post.target)} {op} 1"
        if isinstance(post, ast.AssignStmt):
            return f"{self.expr(post.target)} {post.op} {self.expr(post.value)}"
        return self.expr(post.expr)

# ============================================================ expressions
    def expr(self, e):
        if e is None:
            return ""
        if isinstance(e, ast.IntLit):
            return e.value
        if isinstance(e, ast.FloatLit):
            return e.value
        if isinstance(e, ast.StringLit):
            return '"' + self._escape(e.value) + '"'
        if isinstance(e, ast.BoolLit):
            return "true" if e.value else "false"
        if isinstance(e, ast.NullLit):
            return "null"
        if isinstance(e, ast.Ident):
            return e.name
        if isinstance(e, ast.Binary):
            # String equality: Zig forbids `==` on slices, so lower it to
            # std.mem.eql. This lets Zag programs compare strings naturally.
            if e.op in ("==", "!=") and (
                    self.static_type(e.left) == "string"
                    or self.static_type(e.right) == "string"):
                left = self.expr(e.left)
                right = self.expr(e.right)
                eq = f"std.mem.eql(u8, {left}, {right})"
                return f"({eq})" if e.op == "==" else f"(!{eq})"
            return f"({self.expr(e.left)} {e.op} {self.expr(e.right)})"
        if isinstance(e, ast.ConcatExpr):
            self.used_prelude = True
            return f"zag_concat({e.alloc}, {self.expr(e.left)}, {self.expr(e.right)})"
        if isinstance(e, ast.Unary):
            op = "!" if e.op == "not" else e.op
            return f"({op}{self.expr(e.operand)})"
        if isinstance(e, ast.Call):
            return self._gen_call(e)
        if isinstance(e, ast.Field):
            if e.name == "len":
                kind = self._base_collection_kind(e.base)
                if kind == "list":
                    return f"({self.expr(e.base)}).items.len"
                if kind == "map":
                    return f"({self.expr(e.base)}).count()"
            return f"{self.expr(e.base)}.{e.name}"
        if isinstance(e, ast.Index):
            kind = self._base_collection_kind(e.base)
            if kind == "list":
                return f"({self.expr(e.base)}).items[{self._index_expr(e.index)}]"
            return f"{self.expr(e.base)}[{self._index_expr(e.index)}]"
        if isinstance(e, ast.SliceExpr):
            start = "" if e.start is None else self._index_expr(e.start)
            end = "" if e.end is None else self._index_expr(e.end)
            return f"{self.expr(e.base)}[{start}..{end}]"
        if isinstance(e, ast.ArrayLit):
            return self._gen_array_lit(e)
        if isinstance(e, ast.StructLit):
            return self._gen_struct_lit(e)
        if isinstance(e, ast.IfExpr):
            then_s = self._branch_value(e.then_expr)
            else_s = self._branch_value(e.else_expr)
            cap = ""
            if e.payload:
                if (self._name_used(e.then_expr, e.payload)
                        or self._name_used(e.else_expr, e.payload)):
                    cap = f" |{e.payload}|"
                else:
                    cap = " |_|"  # payload performs the unpack; placeholder required even when unused
            return f"if ({self.expr(e.cond)}){cap} {then_s} else {else_s}"
        if isinstance(e, ast.TryExpr):
            return f"try {self.expr(e.expr)}"
        if isinstance(e, ast.CatchExpr):
            return self._gen_catch(e)
        if isinstance(e, ast.AddressOf):
            return f"&{self.expr(e.operand)}"
        if isinstance(e, ast.Deref):
            return f"{self.expr(e.operand)}.*"
        if isinstance(e, ast.EnumLit):
            return f".{e.name}"
        if isinstance(e, ast.ErrorSetLit):
            return "error{ " + ", ".join(e.variants) + " }"
        if isinstance(e, ast.BuiltinCall):
            args = ", ".join(self.expr(a) for a in e.args)
            return f"@{e.name}({args})"
        if isinstance(e, ast.ImportExpr):
            return f'@import("{self._import_path(e.path)}")'
        if isinstance(e, (ast.StructDecl, ast.EnumDecl, ast.UnionDecl)):
            return self._aggregate_inline(e)
        if isinstance(e, ast.TypeRef):
            return self.zig_type(e)
        raise ZagError(f"代码生成器遇到未知表达式: {type(e).__name__}")

    def _aggregate_inline(self, e):
        """Inline form of aggregate types (used in expression position, e.g. @sizeOf(struct{...}))."""
        if e.methods:
            raise ZagError("聚合类型字面量中的方法请改用声明形式: struct Name { ... }")
        if isinstance(e, ast.EnumDecl):
            items = [v.name + (f" = {self.expr(v.value)}" if v.value is not None else "")
                     for v in e.variants]
            return "enum { " + ", ".join(items) + " }"
        fields = ", ".join(f"{f.name}: {self.zig_type(f.type)}" for f in e.fields)
        kw = "union" if isinstance(e, ast.UnionDecl) else "struct"
        return f"{kw} {{ {fields} }}"

    # ---- Special calls
    def _gen_call(self, e):
        # std.print(...) → std.debug.print(...)
        if isinstance(e.callee, ast.Field) and isinstance(e.callee.base, ast.Ident):
            if e.callee.base.name == "std" and e.callee.name == "print":
                return self._gen_print(e.args)
            if e.callee.base.name == "std" and e.callee.name == "select":
                return self._gen_select(e.args)
        # Resolve the callee to a simple name (either `Name` or `std.Name`)
        callee_name = None
        if isinstance(e.callee, ast.Ident):
            callee_name = e.callee.name
        elif isinstance(e.callee, ast.Field) and isinstance(e.callee.base, ast.Ident) \
                and e.callee.base.name == "std":
            callee_name = "std." + e.callee.name
        # --- std.List / std.Map constructors (explicit allocator) ---
        if callee_name in ("std.List", "std.ArrayList"):
            inner = self._arg_as_type(e.args[0]) if e.args else "i32"
            if len(e.args) >= 2:
                return f"std.array_list.Managed({inner}).init({self.expr(e.args[1])})"
            return f"std.array_list.Managed({inner})"
        if callee_name == "std.Map":
            if len(e.args) >= 2:
                k, v = e.args[0], self.zig_type(e.args[1])
                ktype = "string" if (isinstance(k, ast.TypeRef) and k.name == "string") else self._arg_as_type(k)
                if len(e.args) >= 3:
                    alloc = self.expr(e.args[2])
                    if ktype == "string":
                        return f"std.StringHashMap({v}).init({alloc})"
                    return f"std.AutoHashMap({ktype}, {v}).init({alloc})"
                if ktype == "string":
                    return f"std.StringHashMap({v})"
                return f"std.AutoHashMap({ktype}, {v})"
            return "std.AutoHashMap(i32, i32)"
        # --- collection / string method rewrites ---
        if isinstance(e.callee, ast.Field):
            mname = e.callee.name
            base = e.callee.base
            kind = self._base_collection_kind(base)
            if mname == "set" and kind == "map" and len(e.args) == 2:
                return (f"{self.expr(base)}.put({self.expr(e.args[0])}, "
                        f"{self.expr(e.args[1])}) catch {{}}")
            if mname == "find" and kind == "string" and len(e.args) == 1:
                self.used_prelude = True
                return f"zag_find({self.expr(base)}, {self.expr(e.args[0])})"
            if mname == "to_upper" and kind == "string" and len(e.args) == 1:
                self.used_prelude = True
                return f"zag_to_upper({self.expr(e.args[0])}, {self.expr(base)})"
        # allocator.allocator(n) → allocator.alloc(u8, n)
        if isinstance(e.callee, ast.Field) and e.callee.name == "allocator" and len(e.args) == 1:
            return f"{self.expr(e.callee.base)}.alloc(u8, {self.expr(e.args[0])})"
        callee = self.expr(e.callee)
        args = ", ".join(self.expr(a) for a in e.args)
        return f"{callee}({args})"

    def _gen_print(self, args):
        """std.print -> std.debug.print, choosing the format specifier by static type."""
        specs, vals = [], []
        for a in args:
            specs.append("{s}" if self.static_type(a) == "string" else "{}")
            vals.append(self.expr(a))
        fmt = " ".join(specs) + "\\n"
        tuple_str = ".{" + ", ".join(vals) + "}"
        return f'std.debug.print("{fmt}", {tuple_str})'

    def _gen_select(self, args):
        """std.select("gpa") -> std.heap.page_allocator (unified mapping in v1)."""
        return "std.heap.page_allocator"

    def _gen_array_lit(self, e):
        elem_type = "i32"
        t = self.static_type(e.elems[0])
        if t is not None:
            elem_type = self.TYPE_MAP.get(t, t)
        elems = ", ".join(self.expr(x) for x in e.elems)
        return f"[_]{elem_type}{{ {elems} }}"

    def _gen_struct_lit(self, e):
        fields = ", ".join(f".{name} = {self.expr(v)}" for name, v in e.fields)
        if e.type_name:
            return f"{e.type_name}{{ {fields} }}"
        return f".{{ {fields} }}"

    def _gen_catch(self, e):
        cap = f"|{e.capture}| " if e.capture else ""
        # Zig 0.17 requires captures to be used; auto-omit |err| when unreferenced
        if e.capture and not self._name_used(e.payload, e.capture):
            cap = ""
        if isinstance(e.payload, ast.Block):
            payload = self._block_value(e.payload)
            return f"{self.expr(e.expr)} catch {cap}{payload}"
        if isinstance(e.payload, (ast.ReturnStmt, ast.BreakStmt, ast.ContinueStmt)):
            return f"{self.expr(e.expr)} catch {cap}{self._stmt_text(e.payload)}"
        return f"{self.expr(e.expr)} catch {cap}{self.expr(e.payload)}"

    def _name_used(self, node, name):
        """Whether the AST subtree references the name (used to decide if a catch capture is used)."""
        if node is None:
            return False
        if isinstance(node, ast.Ident):
            return node.name == name
        if isinstance(node, ast.Block):
            return any(self._name_used(st, name) for st in node.stmts)
        for field in vars(node).values():
            if isinstance(field, list):
                if any(self._name_used(x, name) for x in field):
                    return True
            elif hasattr(field, "__dataclass_fields__"):
                if self._name_used(field, name):
                    return True
        return False

    def _stmt_text(self, s):
        """Renders a simple statement as a single line of text (for catch's statement payload)."""
        if isinstance(s, ast.ReturnStmt):
            return f"return {self.expr(s.value)};" if s.value is not None else "return;"
        if isinstance(s, ast.BreakStmt):
            return f"break{(' : ' + s.label) if s.label else ''};"
        if isinstance(s, ast.ContinueStmt):
            return f"continue{(' : ' + s.label) if s.label else ''};"
        raise ZagError(f"不支持的 catch 语句 payload: {type(s).__name__}")

    # ---- Value blocks (if-expression branches / catch payload)
    def _block_value(self, block):
        """Generates a Block as a Zig value block.

         Rules (all verified on Zig 0.17.0):
         - Last statement is an expression statement -> break :blk <expr>; (void operand also legal)
         - Otherwise -> break :blk; (bare break, block type is void)
        """
        saved_out, saved_indent = self.out, self.indent
        self.out, self.indent = [], saved_indent + 1
        stmts = block.stmts
        if stmts and isinstance(stmts[-1], ast.ExprStmt):
            for st in stmts[:-1]:
                self._gen_stmt(st)
            self.emit(f"break :blk {self.expr(stmts[-1].expr)};")
        else:
            for st in stmts:
                self._gen_stmt(st)
            self.emit("break :blk;")
        inner = self.out
        self.out, self.indent = saved_out, saved_indent
        pad = "    " * saved_indent
        return "blk: {\n" + "\n".join(inner) + "\n" + pad + "}"

    def _branch_value(self, branch):
        if isinstance(branch, ast.Block):
            return self._block_value(branch)
        return self.expr(branch)

    # ---- Indexing (Zig indices require usize; i32 needs @intCast)
    def _index_expr(self, e):
        if isinstance(e, ast.IntLit):
            return e.value
        return f"@intCast({self.expr(e)})"

    def _import_path(self, path):
        if path.endswith(".zag"):
            self.pending_imports.append((path, self.source_dir))
            return path[:-4] + ".zig"
        return path

    @staticmethod
    def _escape(s):
        return (s.replace("\\", "\\\\")
                 .replace('"', '\\"')
                 .replace("\n", "\\n")
                 .replace("\t", "\\t")
                 .replace("\r", "\\r")
                 .replace("\0", "\\0"))

# ============================================================ self-mutation detection
    _MUTATING_METHODS = ("append", "appendSlice", "insert", "prepend",
                         "set", "push", "pop", "add")

    def _call_ret_node(self, e):
        """Return the declared return-type node for a Call's callee (or None)."""
        if not isinstance(e, ast.Call):
            return None
        callee = e.callee
        name = None
        if isinstance(callee, ast.Ident):
            name = callee.name
        elif isinstance(callee, ast.Field) and isinstance(callee.base, ast.Ident):
            base = callee.base
            if base.name == "self" and self._current_self_type is not None:
                name = f"{self._current_self_type}.{callee.name}"
            else:
                bt = self.var_types.get(base.name)
                name = f"{bt}.{callee.name}" if bt is not None else f"{base.name}.{callee.name}"
        if name is not None:
            return self.fn_ret_nodes.get(name)
        return None

    def _stmt_suffix(self, e):
        """How to terminate a Call used as a bare statement.

        Returns 'void' (emit plainly), 'error' (append `catch {}`), or
        'value' (prepend `_ =`). Unknown calls default to 'void'.
        """
        node = self._call_ret_node(e)
        if node is None:
            return "void"
        if isinstance(node, ast.ErrorUnionType):
            return "error"
        if isinstance(node, ast.TypeRef) and node.name == "void":
            return "void"
        return "value"

    def _method_mutates_self(self, body):
        """Heuristic: does a method body write to `self` or call a mutating method on self?"""
        if body is None:
            return False
        found = {"mut": False}

        def check_self_write(target):
            if isinstance(target, ast.Field) and isinstance(target.base, ast.Ident) \
                    and target.base.name == "self":
                found["mut"] = True

        def check_self_call(e):
            if isinstance(e, ast.Call) and isinstance(e.callee, ast.Field):
                b = e.callee.base
                # Any method invoked on `self` (directly, e.g. self.advance())
                # or on a field of self (e.g. self.tokens.append()) may mutate
                # self, either directly or transitively. Mark conservatively so the
                # receiver is emitted as a mutable pointer.
                if isinstance(b, ast.Ident) and b.name == "self":
                    found["mut"] = True
                elif (isinstance(b, ast.Field) and isinstance(b.base, ast.Ident)
                      and b.base.name == "self"):
                    found["mut"] = True
                elif e.callee.name in self._MUTATING_METHODS:
                    found["mut"] = True

        def walk_expr(e):
            if e is None or found["mut"]:
                return
            if isinstance(e, ast.Binary):
                walk_expr(e.left)
                walk_expr(e.right)
            elif isinstance(e, ast.ConcatExpr):
                walk_expr(e.left)
                walk_expr(e.right)
            elif isinstance(e, ast.Unary):
                walk_expr(e.operand)
            elif isinstance(e, ast.Call):
                check_self_call(e)
                walk_expr(e.callee)
                for a in e.args:
                    walk_expr(a)
            elif isinstance(e, ast.Field):
                walk_expr(e.base)
            elif isinstance(e, ast.Index):
                walk_expr(e.base)
                walk_expr(e.index)
            elif isinstance(e, ast.IfExpr):
                walk_expr(e.cond)
                walk_expr(e.then_expr)
                walk_expr(e.else_expr)
            elif isinstance(e, ast.StructLit):
                for _, v in e.fields:
                    walk_expr(v)
            elif isinstance(e, ast.SliceExpr):
                walk_expr(e.base)
                if e.start is not None:
                    walk_expr(e.start)
                if e.end is not None:
                    walk_expr(e.end)
            elif isinstance(e, ast.TryExpr):
                walk_expr(e.expr)
            elif isinstance(e, ast.CatchExpr):
                walk_expr(e.expr)
                walk_expr(e.payload)

        def walk_stmt(s):
            if found["mut"]:
                return
            if isinstance(s, ast.AssignStmt):
                check_self_write(s.target)
                walk_expr(s.value)
            elif isinstance(s, ast.IncDecStmt):
                check_self_write(s.target)
            elif isinstance(s, ast.ExprStmt):
                check_self_call(s.expr)
                walk_expr(s.expr)
            elif isinstance(s, ast.ReturnStmt):
                walk_expr(s.value)
            elif isinstance(s, ast.IfStmt):
                walk_expr(s.cond)
                walk_stmt(s.then_stmt)
                if s.else_stmt is not None:
                    walk_stmt(s.else_stmt)
            elif isinstance(s, ast.WhileStmt):
                walk_expr(s.cond)
                walk_stmt(s.body)
            elif isinstance(s, ast.ForStmt):
                for p in (s.init, s.post):
                    if p is not None:
                        walk_stmt(p)
                walk_expr(s.cond)
                walk_stmt(s.body)
            elif isinstance(s, ast.Block):
                for st in s.stmts:
                    walk_stmt(st)
            elif isinstance(s, ast.DeferStmt):
                walk_stmt(s.body)
            elif isinstance(s, ast.ComptimeStmt):
                walk_stmt(s.body)
            elif isinstance(s, ast.VarDecl):
                if s.value is not None:
                    walk_expr(s.value)
            elif isinstance(s, ast.DestructureDecl):
                walk_expr(s.value)

        walk_stmt(body)
        return found["mut"]

# ============================================================ types
    def zig_type(self, t):
        if t is None:
            return "void"
        if isinstance(t, ast.TypeRef):
            return self.TYPE_MAP.get(t.name, t.name)
        if isinstance(t, ast.ErrorSetLit):
            return "error{ " + ", ".join(t.variants) + " }"
        if isinstance(t, ast.OptionalType):
            return "?" + self.zig_type(t.inner)
        if isinstance(t, ast.ErrorUnionType):
            if t.error_set is not None:
                return f"{self.zig_type(t.error_set)}!{self.zig_type(t.inner)}"
            return "!" + self.zig_type(t.inner)
        if isinstance(t, ast.ArrayTypeNode):
            size = "" if t.size is None else self.expr(t.size)
            return f"[{size}]{self.zig_type(t.elem)}"
        if isinstance(t, ast.GenericType):
            return self._zig_generic_type(t)
        return "void"

# ============================================================ static type inference
    def static_type(self, e):
        """Best-effort type inference, mainly to drive std.print format-spec selection."""
        if isinstance(e, ast.StringLit):
            return "string"
        if isinstance(e, ast.ConcatExpr):
            return "string"
        if isinstance(e, ast.IntLit):
            return "int"
        if isinstance(e, ast.FloatLit):
            return "float"
        if isinstance(e, ast.BoolLit):
            return "bool"
        if isinstance(e, ast.Ident):
            return self.var_types.get(e.name)
        if isinstance(e, ast.Binary):
            if e.op in ("==", "!=", "<", "<=", ">", ">=", "and", "or"):
                return "bool"
            lt, rt = self.static_type(e.left), self.static_type(e.right)
            if lt == "float" or rt == "float":
                return "float"
            if lt == "int" and rt == "int":
                return "int"
            return None
        if isinstance(e, ast.Call):
            if isinstance(e.callee, ast.Ident):
                n = e.callee.name
                if n in ("std.List", "std.ArrayList"):
                    return "List"
                if n == "std.Map":
                    return "Map"
                return self.fn_returns.get(n)
            if isinstance(e.callee, ast.Field):
                if e.callee.name == "to_upper":
                    return "string"
                # std.List(...) / std.Map(...) constructors written in expression position
                if isinstance(e.callee.base, ast.Ident) and e.callee.base.name == "std":
                    if e.callee.name in ("List", "ArrayList"):
                        return "List"
                    if e.callee.name == "Map":
                        return "Map"
                if isinstance(e.callee.base, ast.Ident):
                    base = e.callee.base
                    if base.name == "self" and self._current_self_type is not None:
                        base_type = self._current_self_type
                    else:
                        base_type = self.var_types.get(base.name)
                    if base_type is not None:
                        ret = self.fn_returns.get(f"{base_type}.{e.callee.name}")
                        if ret is not None:
                            return ret
                    # myModule.greet() — function from an imported module
                    return self.fn_returns.get(f"{base.name}.{e.callee.name}")
            return None
        if isinstance(e, ast.IfExpr):
            # When both branches have the same static type, take it (e.g. if (c) "a" else "b" -> string)
            lt, rt = self.static_type(e.then_expr), self.static_type(e.else_expr)
            if lt is not None and lt == rt:
                return lt
            return None
        if isinstance(e, ast.Field):
            base_t = self.static_type(e.base)
            if base_t is None and isinstance(e.base, ast.Ident) and e.base.name == "self" \
                    and self._current_self_type is not None:
                base_t = self._current_self_type
            if base_t is not None and base_t in self.struct_fields:
                return self.struct_fields[base_t].get(e.name)
            return None
        if isinstance(e, ast.StructLit):
            return e.type_name or None
        if isinstance(e, ast.BuiltinCall):
            # @typeName / @tagName / @errorName return strings
            if e.name in ("typeName", "tagName", "errorName"):
                return "string"
            return None
        if isinstance(e, ast.Index):
            kind = self._base_collection_kind(e.base)
            if kind == "list":
                tid = self.static_type(e.base)
                if tid is not None and tid.startswith("List:"):
                    return tid[5:]  # the element type id
            return None
        return None


def generate_zig(program, filename="<stdin>", source_dir="."):
    """Convenience entry: AST -> (Zig source, list of imports to compile)."""
    cg = CodeGen(filename, source_dir)
    code = cg.generate(program)
    return code, cg.pending_imports
